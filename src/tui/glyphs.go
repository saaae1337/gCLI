package tui

// ---------- Фирменные знаки и их ASCII-замены ----------
//
// Все знаки интерфейса — константы в самом бинарнике: с диска не
// читается ничего, и на любой системе кадр собирается одинаково.
// Терминалам и шрифтам без юникодной псевдографики (-ascii,
// GCLI_ASCII, слабая локаль или шрифт) кадр всё равно остаётся
// аккуратным: у каждого фирменного знака есть замена из чистого
// ASCII, а клетки остаются на своих местах — выравнивание не плывёт.

// asciiFallbackMap — знак кадра → замена из чистого ASCII.
var asciiFallbackMap = map[rune]rune{
	// Псевдографика.
	'─': '-', '│': '|', '┌': '+', '┐': '+', '└': '+', '┘': '+',
	'╭': '+', '╮': '+', '╰': '+', '╯': '+', '┃': '|', '┄': '-', '┈': '-',
	// Фирменные звёзды и ромбы.
	'◆': '*', '◇': '*', '◈': '*', '✦': '*', '✧': '*',
	'✶': '*', '✷': '*', '✸': '*', '✹': '*', '✺': '*',
	// Стрелки, маркеры, разделители.
	'❯': '>', '›': '>', '▸': '>', '•': '.', '·': '.', '⋯': '.', '…': '.',
	'↑': '^', '↓': 'v', '→': '>', '←': '<', '⇩': 'v',
	// Блоки и полублоки пиксельного арта.
	'░': '.', '▒': '.', '▓': '#', '█': '#', '▀': '^', '▄': '.', '◧': '#',
	// Значки состояний.
	'⚠': '!', '✓': 'v', '☑': 'v', '✕': 'x', '✗': 'x', '⊘': 'x', '✎': '*',
	'⬡': 'o', 'ω': 'w',
}

// asciiFallback — заменить фирменные знаки кадра на ASCII-замены.
// Вызывается на собранном кадре в ASCII-режиме: подмена идёт после
// раскладки, поэтому сетка уже посчитана по исходным знакам и ширины
// клеток гарантированно сходятся с тем, что нарисует терминал.
func asciiFallback(s *Screen) {
	for i := range s.Cells {
		c := &s.Cells[i]
		if c.Cont {
			continue
		}
		if r, ok := asciiFallbackMap[c.R]; ok {
			c.R = r
			c.Rest = "" // хвост кластера (VS16, ZWJ) замене не нужен
		}
	}
}
