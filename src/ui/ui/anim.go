package ui

import (
	"strings"
	"time"
)

// ---------- Анимации появления ----------
//
// Здесь один примитив, который ничего лишнего не рисует:
//
//	RevealLines / RevealLine — строки ответа и результаты инструментов
//	появляются по одной: сначала приглушённым цветом, затем цвет уходит
//	в «норму». Текст читается сразу, но глаз замечает, что строка только
//	что проступила.
//
// Эффект требует цвета: без него затухать нечему, а перерисовка строки
// оставит только мусор. Поэтому всё выключается через canReveal, который
// учитывает -no-color, -ascii, NO_COLOR, GCLI_NO_ANIM, quiet и пайпы.

// animStep — пауза между символами при проявлении. Строка в 40 символов
// проявляется примерно за 0,4 с: быстрее — не успеваешь заметить,
// медленнее — раздражает на каждом ответе.
const animStep = 10 * time.Millisecond

// animLineStep — пауза между строками при проявлении блока.
const animLineStep = 18 * time.Millisecond

// revealMinWidth — уже этой ширины анимация не нужна: на узком
// терминале перерисовка строки мигает.
const revealMinWidth = 24

// revealMaxChars — предел анимируемой длины. Слишком длинная строка
// (дамп лога, таблица) проявляется дольше, чем её успевают прочитать.
const revealMaxChars = 400

// ---------- Пороги и доступность ----------

// canReveal — разрешены ли эффекты появления строк.
//
// Появление строки не требует управления курсором по кадрам логотипа
// и не конфликтует с плоской вёрсткой. Учитывает -no-color, -ascii,
// NO_COLOR, GCLI_NO_ANIM, quiet-режим и пайпы.
func (u *UI) canReveal() bool {
	return u.opts.Animations && u.opts.Color && !u.quiet
}

// ---------- Появление строк ----------

// RevealLines — напечатать строки с эффектом появления.
//
// Сначала печатается заготовка из пустых строк, затем строки проявляются
// по одной: с приглушённым цветом, потом цвет уходит в «норму».
func (u *UI) RevealLines(lines []string) {
	if !u.canReveal() || u.Width() < revealMinWidth {
		for _, l := range lines {
			u.Println(l)
		}
		return
	}
	// Спиннер должен умолкнуть до заготовки: иначе он печатает поверх
	// блока, и тот «едет» на экране.
	u.SpinnerStop()

	// Заготовка.
	for range lines {
		u.RawWrite("\n")
	}
	// Курсор в начало блока.
	if len(lines) > 1 {
		u.RawWrite("\033[" + itoa(len(lines)-1) + "A")
	}
	u.RawWrite("\r")

	// Проявляем по одной строке на «экране».
	for i := range lines {
		if i > 0 {
			u.RawWrite("\n")
		}
		// Приглушённый кадр — строка «проступает».
		// Затухание идёт через dimFrame, а не через обёртку приглушённым
		// цветом: строки приходят уже раскрашенными (баннер, рельс), и
		// чужой цвет гасился бы на первом же сбросе внутри строки.
		u.RawWrite("\033[K" + dimFrame(lines[i]))
		time.Sleep(animLineStep)
		// Нормальный кадр — строка «проявилась».
		u.RawWrite("\r\033[K" + lines[i])
	}
	// Курсор остался на последней строке блока: без перевода строки
	// следующий вывод допишется в неё.
	u.RawWrite("\n")
}

// RevealLine — напечатать одну готовую (уже раскрашенную) строку с
// эффектом появления.
//
// Строка печатается целиком, но сначала приглушённым цветом, затем
// цвет возвращается в норму. Раскраска не разбирается и не собирается
// заново: строка приходит готовой из рельса или блока, и трогать её
// содержимое нельзя.
//
// Как и RevealLines, метод печатает перевод строки в конце: иначе следующий
// вывод дописался бы в конец строки. Раньше перевода не было, и результат
// инструмента в теме Orbit слипался со следующей строкой рельса.
func (u *UI) RevealLine(s string) {
	if !u.canReveal() || u.Width() < revealMinWidth {
		u.Println(s)
		return
	}
	// Спиннер должен умолкнуть до первого кадра: иначе он печатает поверх
	// проявляемой строки и оставляет мусор.
	u.SpinnerStop()
	// Приглушённый кадр, затем нормальный.
	u.Write("\r\033[K" + dimFrame(s))
	time.Sleep(animLineStep)
	u.Write("\r\033[K" + s + "\n")
}

// dimFrame — версия готовой строки, приглушённая целиком.
//
// Простой обёртки вида cDim+s+cReset недостаточно: строка приходит уже
// раскрашенной, и каждый её фрагмент заканчивается сбросом (\033[0m),
// который гасит затухание на первом же переходе. Поэтому dim вставляется
// заново после каждого сброса — тогда гаснут все фрагменты, а не первый.
func dimFrame(s string) string {
	if !strings.Contains(s, cReset) {
		return cDim + s + cReset
	}
	return cDim + strings.ReplaceAll(s, cReset, cReset+cDim) + cReset
}

// TypeLine — напечатать одну строку с проявлением по символам.
//
// Эффект тот же, что у RevealLines, но для одной строки без заготовки.
func (u *UI) TypeLine(s string) {
	if !u.canReveal() || u.Width() < revealMinWidth || runeLen(s) > revealMaxChars {
		u.Println(s)
		return
	}

	r := []rune(s)
	for k := 1; k <= len(r); k++ {
		// Новое приходит приглушённым, старое — обычным.
		dim := string(r[:k-1])
		head := u.c(u.pal.Muted, string(r[k-1]))
		u.RawWrite("\r\033[K" + dim + head)
		time.Sleep(animStep)
	}
	// Финал: обычная печать, чтобы не осталось «курсива».
	u.RawWrite("\r\033[K" + s)
}
