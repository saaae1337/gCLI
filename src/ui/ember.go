// ---------- Стиль «Ночной город» ----------
//
// Концепт интерфейса — OpenCode: плоская вёрстка, метки сообщений,
// маркер вызова инструмента «*», «зубец» результата «:», холодный синий
// акцент. Ничего не рисует сам терминал — только интерфейс: тот же вид
// в Terminal.app, iTerm2, linux-консоли и cmd.exe на Windows 10/11.
//
//  1. Разметка. Событие начинается маркером, результат идёт строкой ниже:
//
//      * read_file  src/ui/ui.go
//        : 481 строка | 3ms
//
//  2. Маркер события — «*». Рисуется одинаково везде и не зависит от шрифта.
//
//  3. Акцент — синий, и он НЕ занимает слот «красный». Ошибка остаётся
//     красной: git diff и ls в том же терминале выглядят согласованно.
//
//  4. Второй акцент (фиолет) не пересекается со «слотом ошибки» и на 16
//     цветах не сливается с синим.
//
//  5. Приглушённый приём «перелив» вместо «летающих» стрелок: у каждого
//     основного цвета есть двойник послабее, и анимация живёт на этой паре.

// themeEmber - каноническое имя темы. Историческое значение сохранено:
// старые config.json читаются без миграций. Стиль один - «Ночной город».
const themeEmber = "ember"

// normalizeTheme - свести имя темы к канону. Раньше тем было несколько
// (orbit, claude, nord, matrix, mono) и функция разбирала алиасы; после
// унификации остаётся одно правило: что бы ни стояло в старом config.json
// («theme": "orbit", "claude", «mono»...), оформление - «Ночной город».
func normalizeTheme(theme string) string {
	return themeEmber
}

