// ---------- Примитивы ----------

// emberMark — маркер события (вызов инструмента, шаг, раздел). Цвет приходит
// от категории инструмента: у каждого свой оттенок, и глаз считывает тип
// вызова не читая названия.
func (u *UI) emberMark(color string) string {
	return u.c(color, u.g.Star)
}

// emberTickGlyph — «зубец» перед результатом. Читается как отпечаток
// инструмента: вызов отмечен ромбом, след от него — «зубцом».
// Это запасной вариант для наборов, у которых Glyphs.Tick пуст.
const emberTickGlyph = "⎿"

// emberTickOf — «зубец» для текущего терминала.
//
// Символ берётся из набора псевдографики, а не пишется прямо здесь:
// в ASCII-режиме (-ascii, GCLI_ASCII) глиф «⎿» печатать нельзя, и без
// подстановки терминал рисовал бы «кракозябру» на месте каждого результата.
func (u *UI) emberTickOf() string {
	if u.g.Tick != "" {
		return u.g.Tick
	}
	if u.g.Unicode {
		return emberTickGlyph
	}
	return ">-"
}

// emberTail — продолжение строки события: маркер без цвета.
func (u *UI) emberTail() string { return u.c(u.pal.Muted, u.emberTickOf()) }

// emberRule — тонкая линия-разделитель в полосу: мягче рамки, но заметнее
// пунктира, который в этом стиле занят разделителем колонок.
func (u *UI) emberRule(width int) string {
	if width < 1 {
		width = 1
	}
	return u.c(u.pal.Muted, strings.Repeat(u.g.RuleChar, width))
}

// emberRuleTail — хвост заголовка: линия впритык к правому краю.
func (u *UI) emberRuleTail(width int) string {
	if width < 1 {
		return ""
	}
	return u.c(u.pal.Muted, " "+strings.Repeat(u.g.RuleChar, width-1))
}

// emberStatusGlyph — иконка статуса результата.
func (u *UI) emberStatusGlyph(status string) (string, string) {
	switch status {
	case "fail", "error":
		return u.g.Cross, u.pal.Err
	case "denied":
		return "⊘", u.pal.Warn
	case "skip":
		return "⊘", u.pal.Muted
	default:
		return u.g.Check, u.pal.OK
	}
}

// ---------- Размышления ----------

// ThinkMarker — напечатать маркер открытия потока размышлений и погасить
// строку ожидания.
//
// Отдельный метод, потому что маркер нужен в трёх местах: перед первым
// куском вслепую, по Ctrl+O (поток открывается посреди хода) и при
// разовом показе накопленного. Раньше эту роль играл ThinkStart, но он
// ставил флаг think, не печатая заголовок, — и первый же кусок после него
// уходил в экран без подписи «размышления».
func (u *UI) ThinkMarker() {
	u.SpinnerStop()
	u.think = true
	if sink := u.sink(); sink != nil {
		sink.BeginThink()
		return
	}
	u.Println("  " + u.emberMark(u.pal.Muted) + " " + u.c(u.pal.Muted, u.g.Dash+" размышления"))
}

// ThinkChunk — принять кусок размышлений и напечатать его в потоке.
//
// Поток открывает не ThinkChunk, а ThinkMarker: иначе первый кусок, пришедший
// после Ctrl+O посреди хода, начинался бы без заголовка и выглядел бы как
// обычный ответ модели. Если маркера не было — печатаем его здесь, чтобы
// поток не потерялся.
//
// Печать приглушённая — размышления фон хода, и обычным цветом они
// перетягивали бы внимание с ответа модели.
func (u *UI) ThinkChunk(s string) {
	if s == "" {
		return
	}
	if sink := u.sink(); sink != nil {
		sink.ThinkText(s)
		return
	}
	if !u.think {
		u.ThinkMarker()
	}
	u.Print(u.c(u.pal.Muted, s))
}

// ThinkEnd — закрыть поток размышлений.
//
// Перевод строки обязателен: иначе ответ модели допишется в хвост мысли.
// Если размышлений так и не было, перевод не нужен — ничего не нарисовано.
func (u *UI) ThinkEnd() {
	if sink := u.sink(); sink != nil {
		sink.EndThink()
		u.think = false
		return
	}
	if u.think {
		u.SpinnerStop()
		u.think = false
	}
	// Перевод строки нужен всегда, а не только когда поток «открыт»:
	// сворачивание по Ctrl+O тоже должно увести курсор на новую строку,
	// иначе следующий ответ допишется в хвост последней мысли.
	u.Println("")
}

// ThinkHidden — размышления скрыты и показаны разово, одним блоком.
//
// Это режим по умолчанию: пока модель думает, на экране висит только строка
// ожидания с котом, а текст мыслей копится в буфере приложения. Пользователь
// открывает его сам, нажатием Ctrl+O.
//
// Печать приглушённая, маркер — только если поток ещё не открыт: иначе
// Ctrl+O посреди хода печатал бы второй заголовок «размышления» поверх
// первого. Ширина на минус шесть — четыре колонки отступа плюс запас, чтобы
// строки не упирались в правый край.
func (u *UI) ThinkHidden(text string) {
	if strings.TrimSpace(text) == "" {
		return
	}
	if sink := u.sink(); sink != nil {
		sink.BeginThink()
		sink.ThinkText(text)
		sink.EndThink()
		return
	}
	if !u.think {
		u.ThinkMarker()
	}
	// Весь блок одной строкой: размышления — это поток мысли, у него нет
	// абзацной структуры, и перенос по словам рвёт фразы на куски.
	for _, l := range wrap(core.OneLine(text), u.Width()-6) {
		u.Print(u.c(u.pal.Muted, l))
	}
}
