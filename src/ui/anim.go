package ui

// ---------- Вывод строк ----------
//
// Эффекты появления (проявление по символам, затухание строк, бегущие
// волны) удалены: анимации перерисовкой утомляют глаз, добавляют лаг
// и оставляют мусор в терминалах с неполной поддержкой ANSI. Терминальный
// интерфейс Claude Code просто печатает строки — так и здесь.

// RevealLines - напечатать строки как есть.
func (u *UI) RevealLines(lines []string) {
	for _, l := range lines {
		u.Println(l)
	}
}

// RevealLine - напечатать одну готовую (уже раскрашенную) строку.
func (u *UI) RevealLine(s string) {
	u.Println(s)
}

// TypeLine - напечатать одну строку как есть.
func (u *UI) TypeLine(s string) {
	u.Println(s)
}
