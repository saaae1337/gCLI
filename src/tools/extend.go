package tools

import (
	"context"
	"fmt"
)

// ---------- Продление хода (extend_turns) ----------
//
// Инструмент существует из-за одного наблюдения: лимит итераций раньше был
// неразговариваемой стеной. Модель упиралась в него на середине работы,
// инструменты отключались, и всё собранное уходило в принудительный отчёт.
// Теперь лимит можно попросить увеличить — но с объяснением, что именно
// осталось сделать.
//
// Объяснение здесь не формальность. «Продли» не проходит (минимум 20
// символов), и это лучший известный способ заставить модель посмотреть на
// свою же задачу: пока она формулирует причину, она вынуждена ответить на
// вопрос «что я вообще делаю и зачем мне ещё время».

var schemaExtend = `{"type":"object","properties":{"reason":{"type":"string","description":"Что именно осталось сделать и почему этого не хватает — одна-двумя фразами, минимум 20 символов"},"n":{"type":"integer","description":"На сколько итераций продлить (не обязательно; по умолчанию — размер шага из конфига)"}}}`

func registerExtendTool(r *Registry) {
	r.registerBound("extend_turns",
		"Продлить лимит итераций этого хода, когда работы честно много, а лимит заканчивается. "+
			"Обязательно объясни одной-двумя фразами, что осталось сделать и почему не помещается: "+
			"обоснование обязательно, без него продление не выдаётся. Не злоупотреби: продление "+
			"отклоняется, если последние ходы повторяют одни и те же вызовы или израсходован бюджет. "+
			"Проверь остаток в self_status.",
		schemaExtend, "plan", false, func(r *Registry) Handler { return r.hExtendTurns })
}

// hExtendTurns — продлить ход.
func (r *Registry) hExtendTurns(_ context.Context, m map[string]any) (Result, error) {
	if r.env.Extend == nil {
		if r.env.Depth > 0 {
			return Result{}, fmt.Errorf("продление хода доступно только главному агенту: " +
				"у субагента свой лимит итераций, задавай его в tools при spawn")
		}
		return Result{}, fmt.Errorf("инструмент недоступен в этом окружении")
	}

	reason := ArgStr(m, "reason")
	n := ArgInt(m, "n", 0)
	if n < 0 {
		n = 0
	}

	granted, msg, err := r.env.Extend(reason, n)
	if err != nil {
		return Result{}, err
	}
	sum := fmt.Sprintf("продлено на %d итераций", granted)
	return Result{Text: msg, Summary: sum}, nil
}
