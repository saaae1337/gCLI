// builtinByName — индекс встроенных навыков.
func builtinByName(name string) *BuiltinSkill {
	for i := range builtinSkills {
		if builtinSkills[i].Name == name {
			return &builtinSkills[i]
		}
	}
	return nil
}

// BuiltinSkills — все встроенные навыки (отсортированы по имени).
func BuiltinSkills() []BuiltinSkill {
	out := append([]BuiltinSkill(nil), builtinSkills...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// loadBuiltinSkills — встроенные навыки в виде объектов Skill.
// Пользовательские навыки с теми же именами их перекрывают (в LoadSkills).
func loadBuiltinSkills(userNames map[string]bool) []Skill {
	var out []Skill
	for _, s := range builtinSkills {
		if userNames[s.Name] {
			continue
		}
		out = append(out, Skill{
			Name:  s.Name,
			Desc:  s.Desc,
			Body:  s.Body,
			Path:  "(встроенный)",
			Scope: "встроенный",
		})
	}
	return out
}

